export async function seedReference() {
  const db = useDb()
  await db.batch([
    db.insert(schema.killers).values(KILLERS).onConflictDoNothing(),
    db.insert(schema.maps).values(MAPS).onConflictDoNothing(),
    db.insert(schema.mates).values(MATES).onConflictDoNothing(),
    db.insert(schema.events).values(EVENTS).onConflictDoNothing(),
  ])
}
